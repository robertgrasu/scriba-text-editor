sources = []
inc = ["// generated by gents.py: the highlight queries of the tree-sitter grammars (bytes of the .scm files)\n"]
for (lid, fn, disp, exts, dirs, extra, queries) in LANGS:
    for (srel, drel) in dirs:
        cp_tree(os.path.join(DL, srel.replace("/", os.sep)), os.path.join(OUT, drel.replace("/", os.sep)))
        for f in sorted(os.listdir(os.path.join(OUT, drel.replace("/", os.sep)))):
            if f in ("parser.c", "scanner.c", "scanner.cc"):
                sources.append(drel + "/" + f)
    for (srel, drel) in extra:
        d = os.path.join(OUT, drel.replace("/", os.sep))
        if os.path.isdir(d):
            shutil.rmtree(d)
        shutil.copytree(os.path.join(DL, srel.replace("/", os.sep)), d, ignore=shutil.ignore_patterns("*.js", "*.json", "*.ts", "*.md"))
    q = b""
    for qf in queries:
        q += open(os.path.join(DL, qf.replace("/", os.sep)), "rb").read() + b"\n"
    arr = ",".join(str(b) for b in q)
    inc.append("static const unsigned char TSQ_%s[] = {%s};\nstatic const int TSQ_%s_N = %d;\n" % (lid, arr, lid, len(q)))
    print(lid, len(q), "bytes of queries")

